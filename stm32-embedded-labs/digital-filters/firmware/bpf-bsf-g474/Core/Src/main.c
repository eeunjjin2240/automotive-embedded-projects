// 1. BPF 계산 함수
float apply_bpf(float x_now) {
    // 차분 방정식: y[n] = b0*x[n] + ... - a1*y[n-1] - ...
    float y_now = (BPF_B0 * x_now) + (BPF_B1 * bpf_x1) + (BPF_B2 * bpf_x2)
                                   - (BPF_A1 * bpf_y1) - (BPF_A2 * bpf_y2);

    // 상태 변수 업데이트 (Shift)
    bpf_x2 = bpf_x1; bpf_x1 = x_now;
    bpf_y2 = bpf_y1; bpf_y1 = y_now;

    return y_now;
}

// 2. BSF 계산 함수
float apply_bsf(float x_now) {
    float y_now = (BSF_B0 * x_now) + (BSF_B1 * bsf_x1) + (BSF_B2 * bsf_x2)
                                   - (BSF_A1 * bsf_y1) - (BSF_A2 * bsf_y2);

    // 상태 변수 업데이트
    bsf_x2 = bsf_x1; bsf_x1 = x_now;
    bsf_y2 = bsf_y1; bsf_y1 = y_now;

    return y_now;
}

// --- ADC 콜백 (100us 마다 실행) ---
void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef* hadc)
{
  if(hadc->Instance == ADC1)
  {
    // 1. ADC 입력 읽기
    float input_val = (float)HAL_ADC_GetValue(&hadc1);

    // 2. DC 오프셋 제거 (AC 성분만 필터링하기 위해)
    // 0~4095의 중간값인 2048을 뺍니다.
    float ac_input = input_val - 2048.0f;

    // 3. 필터 계산
    float bpf_out = apply_bpf(ac_input);
    float bsf_out = apply_bsf(ac_input);

    // 4. DC 오프셋 복구 (DAC 출력을 위해)
    float bpf_dac = bpf_out + 2048.0f;
    float bsf_dac = bsf_out + 2048.0f;

    // 5. DAC 출력
    // DAC1 Channel 1 (PA4) -> BPF 출력
    HAL_DAC_SetValue(&hdac1, DAC_CHANNEL_1, DAC_ALIGN_12B_R, (uint32_t)CLAMP(bpf_dac));

    // DAC1 Channel 2 (PA5) -> BSF 출력
    HAL_DAC_SetValue(&hdac1, DAC_CHANNEL_2, DAC_ALIGN_12B_R, (uint32_t)CLAMP(bsf_dac));
  }
}

