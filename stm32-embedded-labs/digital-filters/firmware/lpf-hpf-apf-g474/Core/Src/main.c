// 1차 LPF 필터 적용 함수 (알고리즘은 동일)
float apply_lpf(float x_now)
{
    // 차분 방정식: y(n) = b0*x(n) + b1*x(n-1) - a1*y(n-1)
    float y_now = (LPF_B0 * x_now) + (LPF_B1 * lpf_x_prev) - (LPF_A1 * lpf_y_prev);

    // 다음 계산을 위해 현재 값을 이전 값으로 업데이트
    lpf_x_prev = x_now;
    lpf_y_prev = y_now;

    return y_now;
}

// 1차 HPF 필터 적용 함수 (알고리즘은 동일)
float apply_hpf(float x_now)
{
    float y_now = (HPF_B0 * x_now) + (HPF_B1 * hpf_x_prev) - (HPF_A1 * hpf_y_prev);

    hpf_x_prev = x_now;
    hpf_y_prev = y_now;

    return y_now;
}

float apply_apf(float x_now)
{
    // 수식: y[n] = 0.7*x[n] + x[n-1] - 0.7*y[n-1]
    float y_now = (APF_ALPHA * x_now) - apf_x_prev + (APF_ALPHA * apf_y_prev);

    // 상태 업데이트
    apf_x_prev = x_now;
    apf_y_prev = y_now;

    return y_now;
}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef* hadc)
{
  if(hadc->Instance == ADC1)
  {
    // 1. ADC 값 읽기 (0 ~ 4095)
    float input_val = (float)HAL_ADC_GetValue(&hadc1);

    // 2. 필터 적용 (둘 중 하나 선택)
    float lpf_output_val = apply_lpf(input_val);

    // --- HPF를 사용하려면 아래 3줄의 주석을 해제하고 위 1줄을 주석 처리 ---
    float ac_input = input_val - 2048.0f; // DC 오프셋 제거

    float hpf_output = apply_hpf(ac_input);
    float hpf_output_val = hpf_output + 2048.0f; // DC 오프셋 복원

    float apf_output = apply_apf(ac_input);
    float apf_output_val = apf_output + 2048.0f; // DC 오프셋 복원




    // 3. DAC로 값 출력 (0~4095 범위 클리핑)
    if (lpf_output_val < 0.0f) lpf_output_val = 0.0f;
    if (lpf_output_val > 4095.0f) lpf_output_val = 4095.0f;

    if (hpf_output_val < 0.0f) hpf_output_val = 0.0f;
    if (hpf_output_val > 4095.0f) hpf_output_val = 4095.0f;

    if (apf_output_val < 0.0f) apf_output_val = 0.0f;
    if (apf_output_val > 4095.0f) apf_output_val = 4095.0f;

    HAL_DAC_SetValue(&hdac1, DAC_CHANNEL_1, DAC_ALIGN_12B_R, (uint32_t)lpf_output_val);
    HAL_DAC_SetValue(&hdac1, DAC_CHANNEL_2, DAC_ALIGN_12B_R, (uint32_t)hpf_output_val);
    HAL_DAC_SetValue(&hdac2, DAC_CHANNEL_1, DAC_ALIGN_12B_R, (uint32_t)apf_output_val);
  }
}

